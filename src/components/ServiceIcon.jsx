function inferIconKey(service) {
  if (service?.iconKey) return service.iconKey;
  const text = `${service?.slug || ''} ${service?.title || ''}`.toLowerCase();
  if (text.includes('web') || text.includes('dev')) return 'code';
  if (text.includes('graphic')) return 'palette';
  if (text.includes('video')) return 'video';
  if (text.includes('content') || text.includes('copy') || text.includes('writ')) return 'pen';
  if (text.includes('strategy')) return 'compass';
  if (text.includes('social')) return 'share';
  if (text.includes('seo') || text.includes('search')) return 'search';
  if (text.includes('market')) return 'megaphone';
  if (text.includes('brand')) return 'layers';
  if (text.includes('ai') || text.includes('auto')) return 'cpu';
  return 'sparkles';
}

